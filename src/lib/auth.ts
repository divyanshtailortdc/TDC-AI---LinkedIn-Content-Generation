import 'server-only'

import { passkey } from '@better-auth/passkey'
import { betterAuth } from 'better-auth'
import { drizzleAdapter } from 'better-auth/adapters/drizzle'
import { nextCookies } from 'better-auth/next-js'
import { admin } from 'better-auth/plugins'
import { db } from '~/db'
import {
  authAccountsTable,
  authPasskeysTable,
  authSessionsTable,
  authUsersTable,
  authVerificationsTable
} from '~/db/schema'
import { env } from '~/env'
import { ADMIN_ROLES, parseAdminUserIds, USER_ROLE } from './roles'

const APP_NAME = 'TDC LinkedIn Content Engine'

const isGoogleSignInEnabled = Boolean(
  env.GOOGLE_CLIENT_ID && env.GOOGLE_CLIENT_SECRET
)
const isLinkedInSignInEnabled = Boolean(
  env.LINKEDIN_CLIENT_ID && env.LINKEDIN_CLIENT_SECRET
)

/** The social sign-ins with credentials set, in the order the buttons show. */
export const socialSignInProviders = [
  ...(isLinkedInSignInEnabled ? (['linkedin'] as const) : []),
  ...(isGoogleSignInEnabled ? (['google'] as const) : [])
]

export const adminUserIds = parseAdminUserIds(env.ADMIN_USER_IDS)

const appUrl = env.BETTER_AUTH_URL ?? env.NEXT_PUBLIC_APP_URL
// The app is also opened at NEXT_PUBLIC_APP_URL (e.g. a LAN address in
// development); requests from there are accepted too.
const trustedOrigins = [...new Set([appUrl, env.NEXT_PUBLIC_APP_URL])]

export const auth = betterAuth({
  appName: APP_NAME,
  baseURL: appUrl,
  // Undefined falls back to Better Auth's own BETTER_AUTH_SECRET lookup, which
  // refuses to start in production without one.
  secret: env.BETTER_AUTH_SECRET,
  trustedOrigins,

  database: drizzleAdapter(db, {
    provider: 'pg',
    // auth_* tables: `accounts` is the LinkedIn identity table.
    schema: {
      user: authUsersTable,
      session: authSessionsTable,
      account: authAccountsTable,
      verification: authVerificationsTable,
      passkey: authPasskeysTable
    }
  }),
  advanced: {
    // uuid ids generated by Postgres, like every other table, so
    // accounts.user_id can reference auth_users.id as a uuid.
    database: { generateId: 'uuid' }
  },

  // Sessions are checked against the database on every request (no cookie
  // cache), so signing out or an admin revoking a session takes effect
  // immediately.

  socialProviders: {
    ...(isGoogleSignInEnabled && {
      google: {
        clientId: env.GOOGLE_CLIENT_ID!,
        clientSecret: env.GOOGLE_CLIENT_SECRET!,
        prompt: 'select_account' as const
      }
    }),
    // "Sign In with LinkedIn using OpenID Connect" (profile, email, openid).
    // Unrelated to the LinkedIn identities in `accounts`.
    ...(isLinkedInSignInEnabled && {
      linkedin: {
        clientId: env.LINKEDIN_CLIENT_ID!,
        clientSecret: env.LINKEDIN_CLIENT_SECRET!
      }
    })
  },

  account: {
    accountLinking: {
      // A Google or LinkedIn sign-in links to the existing user with the same
      // email, even one whose email was never confirmed (left from the old
      // password sign-up, or made by an admin). Safe now that there are no
      // passwords: nobody can have registered the address first and kept a
      // way in. The provider must still report the email as verified, as
      // neither is a trusted provider.
      requireLocalEmailVerified: false
    }
  },

  plugins: [
    // Passkeys are added by a signed-in user (from the sidebar), then used to
    // sign in. They are bound to BETTER_AUTH_URL's host name.
    passkey({
      rpID: new URL(appUrl).hostname,
      rpName: APP_NAME,
      origin: trustedOrigins
    }),
    admin({
      defaultRole: USER_ROLE,
      adminRoles: ADMIN_ROLES,
      adminUserIds
    }),
    // Must stay last: it lets auth.api calls in Server Actions set cookies.
    nextCookies()
  ]
})

export type Session = typeof auth.$Infer.Session
export type SessionUser = Session['user']
