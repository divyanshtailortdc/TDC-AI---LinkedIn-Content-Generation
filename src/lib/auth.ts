import 'server-only'

import { passkey } from '@better-auth/passkey'
import { betterAuth } from 'better-auth'
import { drizzleAdapter } from 'better-auth/adapters/drizzle'
import { nextCookies } from 'better-auth/next-js'
import { admin } from 'better-auth/plugins'
import { db } from '~/db'
import {
  authAccountsTable,
  authPasskeysTable,
  authSessionsTable,
  authUsersTable,
  authVerificationsTable
} from '~/db/schema'
import { env } from '~/env'
import {
  PASSWORD_MAX_LENGTH,
  PASSWORD_MIN_LENGTH,
  SOCIAL_PROVIDER_IDS,
  type SocialProvider
} from './auth-providers'
import { ADMIN_ROLES, parseAdminUserIds, USER_ROLE } from './roles'

const APP_NAME = 'TDC Content Engine'

/** Each social provider's credentials; a provider is offered when both are set. */
const SOCIAL_CREDENTIALS: Record<
  SocialProvider,
  { clientId?: string; clientSecret?: string }
> = {
  google: {
    clientId: env.GOOGLE_CLIENT_ID,
    clientSecret: env.GOOGLE_CLIENT_SECRET
  }
}

/** The social sign-ins with credentials set, in the order the buttons show. */
export const socialSignInProviders: SocialProvider[] =
  SOCIAL_PROVIDER_IDS.filter(
    id => SOCIAL_CREDENTIALS[id].clientId && SOCIAL_CREDENTIALS[id].clientSecret
  )

/** A provider's credentials, when it is offered. */
const credentialsOf = (id: SocialProvider) =>
  socialSignInProviders.includes(id)
    ? {
        clientId: SOCIAL_CREDENTIALS[id].clientId!,
        clientSecret: SOCIAL_CREDENTIALS[id].clientSecret!
      }
    : null
const googleCredentials = credentialsOf('google')

export const adminUserIds = parseAdminUserIds(env.ADMIN_USER_IDS)

const appUrl = env.BETTER_AUTH_URL ?? env.NEXT_PUBLIC_APP_URL
// The app is also opened at NEXT_PUBLIC_APP_URL (e.g. a LAN address in
// development); requests from there are accepted too.
const trustedOrigins = [...new Set([appUrl, env.NEXT_PUBLIC_APP_URL])]

export const auth = betterAuth({
  appName: APP_NAME,
  baseURL: appUrl,
  // Undefined falls back to Better Auth's own BETTER_AUTH_SECRET lookup, which
  // refuses to start in production without one.
  secret: env.BETTER_AUTH_SECRET,
  trustedOrigins,

  database: drizzleAdapter(db, {
    provider: 'pg',
    // auth_* tables: `accounts` is the content identity table.
    schema: {
      user: authUsersTable,
      session: authSessionsTable,
      account: authAccountsTable,
      verification: authVerificationsTable,
      passkey: authPasskeysTable
    }
  }),
  advanced: {
    // uuid ids generated by Postgres, like every other table, so
    // accounts.user_id can reference auth_users.id as a uuid.
    database: { generateId: 'uuid' }
  },

  // A signed session cookie answers most session checks without the
  // database; every page load and router.refresh() made one. The trade-off:
  // a session revoked or banned elsewhere, or a role change, takes up to
  // maxAge to take effect. Signing out on this browser clears the cookie
  // at once.
  session: {
    cookieCache: { enabled: true, maxAge: 60 }
  },

  // Sign-in only (src/lib/auth-providers.ts); unrelated to the identities in
  // `accounts` and to publishing connections.
  socialProviders: {
    ...(googleCredentials && {
      google: { ...googleCredentials, prompt: 'select_account' as const }
    })
  },

  // Email and password sign-up and sign-in. The app sends no email, so the
  // address is never confirmed: the user is signed in straight after
  // signing up, with emailVerified false.
  emailAndPassword: {
    enabled: true,
    autoSignIn: true,
    minPasswordLength: PASSWORD_MIN_LENGTH,
    maxPasswordLength: PASSWORD_MAX_LENGTH
  },

  account: {
    accountLinking: {
      // A social sign-in links to the existing user with the same email
      // only when that user's email is confirmed. Must stay true now that
      // anyone can sign up with a password and an unconfirmed address:
      // otherwise someone could register a victim's email first, and keep
      // their password way in after the victim signs in with Google. The
      // provider must also report the email as verified, as none is a
      // trusted provider.
      requireLocalEmailVerified: true
    }
  },

  plugins: [
    // Passkeys are added by a signed-in user (from the sidebar), then used to
    // sign in. They are bound to BETTER_AUTH_URL's host name.
    passkey({
      rpID: new URL(appUrl).hostname,
      rpName: APP_NAME,
      origin: trustedOrigins
    }),
    admin({
      defaultRole: USER_ROLE,
      adminRoles: ADMIN_ROLES,
      adminUserIds
    }),
    // Must stay last: it lets auth.api calls in Server Actions set cookies.
    nextCookies()
  ]
})

export type Session = typeof auth.$Infer.Session
export type SessionUser = Session['user']
