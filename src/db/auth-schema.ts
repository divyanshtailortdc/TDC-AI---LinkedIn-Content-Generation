import {
  boolean,
  index,
  integer,
  pgTable,
  text,
  timestamp,
  uuid
} from 'drizzle-orm/pg-core'

// ---------------------------------------------------------------------------
// Better Auth tables (better-auth 1.6.11 core schema + admin plugin fields,
// and the passkey plugin's table)
//
// Prefixed with auth_ because `accounts` is already the LinkedIn identity
// table. src/lib/auth.ts maps Better Auth's user/session/account/verification/
// passkey models onto these tables; the property names below are the field names
// Better Auth expects, so they must not be renamed.
// ---------------------------------------------------------------------------

const timestamps = {
  createdAt: timestamp('created_at', { mode: 'date', withTimezone: true })
    .notNull()
    .defaultNow(),
  updatedAt: timestamp('updated_at', { mode: 'date', withTimezone: true })
    .notNull()
    .defaultNow()
}

// Ids are generated by Postgres: auth.ts sets `generateId: 'uuid'`.
const id = () => uuid('id').defaultRandom().primaryKey()

export const authUsersTable = pgTable('auth_users', {
  id: id(),
  name: text('name').notNull(),
  email: text('email').notNull().unique(),
  emailVerified: boolean('email_verified').default(false).notNull(),
  image: text('image'),
  // Admin plugin. None of these can be set by the user (input: false in the
  // plugin), only by an admin endpoint or a reviewed database update.
  role: text('role').default('user'),
  banned: boolean('banned').default(false),
  banReason: text('ban_reason'),
  banExpires: timestamp('ban_expires', { mode: 'date', withTimezone: true }),
  ...timestamps
})

export const authSessionsTable = pgTable(
  'auth_sessions',
  {
    id: id(),
    token: text('token').notNull().unique(),
    expiresAt: timestamp('expires_at', {
      mode: 'date',
      withTimezone: true
    }).notNull(),
    ipAddress: text('ip_address'),
    userAgent: text('user_agent'),
    userId: uuid('user_id')
      .notNull()
      .references(() => authUsersTable.id, { onDelete: 'cascade' }),
    // Admin plugin: the admin who started this session by impersonating the user.
    impersonatedBy: text('impersonated_by'),
    ...timestamps
  },
  table => [index('auth_sessions_user_idx').on(table.userId)]
)

/** Sign-in providers of a user: one row per provider (Google). */
export const authAccountsTable = pgTable(
  'auth_accounts',
  {
    id: id(),
    accountId: text('account_id').notNull(),
    providerId: text('provider_id').notNull(),
    userId: uuid('user_id')
      .notNull()
      .references(() => authUsersTable.id, { onDelete: 'cascade' }),
    accessToken: text('access_token'),
    refreshToken: text('refresh_token'),
    idToken: text('id_token'),
    accessTokenExpiresAt: timestamp('access_token_expires_at', {
      mode: 'date',
      withTimezone: true
    }),
    refreshTokenExpiresAt: timestamp('refresh_token_expires_at', {
      mode: 'date',
      withTimezone: true
    }),
    scope: text('scope'),
    // Part of Better Auth's core schema; always empty, as passwords are off.
    password: text('password'),
    ...timestamps
  },
  table => [index('auth_accounts_user_idx').on(table.userId)]
)

/** Short-lived values Better Auth keeps between requests, e.g. Google sign-in state. */
export const authVerificationsTable = pgTable(
  'auth_verifications',
  {
    id: id(),
    identifier: text('identifier').notNull(),
    value: text('value').notNull(),
    expiresAt: timestamp('expires_at', {
      mode: 'date',
      withTimezone: true
    }).notNull(),
    ...timestamps
  },
  table => [index('auth_verifications_identifier_idx').on(table.identifier)]
)

/** Passkeys a user has added (@better-auth/passkey). */
export const authPasskeysTable = pgTable(
  'auth_passkeys',
  {
    id: id(),
    name: text('name'),
    publicKey: text('public_key').notNull(),
    userId: uuid('user_id')
      .notNull()
      .references(() => authUsersTable.id, { onDelete: 'cascade' }),
    credentialID: text('credential_id').notNull(),
    counter: integer('counter').notNull(),
    deviceType: text('device_type').notNull(),
    backedUp: boolean('backed_up').notNull(),
    transports: text('transports'),
    aaguid: text('aaguid'),
    createdAt: timestamp('created_at', {
      mode: 'date',
      withTimezone: true
    }).defaultNow()
  },
  table => [
    index('auth_passkeys_user_idx').on(table.userId),
    index('auth_passkeys_credential_id_idx').on(table.credentialID)
  ]
)

export type AuthUser = typeof authUsersTable.$inferSelect
export type AuthSession = typeof authSessionsTable.$inferSelect
